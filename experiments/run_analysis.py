"""Single scripted run: frozen protocol -> all results artifacts + site data.

Usage: python experiments/run_analysis.py
Everything under results/ and site/data/ is generated by this script only.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from factor_model import backtest as bt
from factor_model import diagnostics as dg
from factor_model.data import build_bundle
from factor_model.regression import (MODELS, benjamini_hochberg,
                                     excess_returns, fit_factor_model,
                                     rolling_beta)

RESULTS = ROOT / "results"
SITE_DATA = ROOT / "site" / "data"


def _clean(obj):
    """Recursively replace NaN/inf with None so output is strict JSON."""
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_clean(v) for v in obj]
    if isinstance(obj, float) and (obj != obj or obj in (float("inf"), float("-inf"))):
        return None
    return obj


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(_clean(obj), indent=2, default=str))


def main() -> None:
    protocol = yaml.safe_load((ROOT / "experiments/protocol.yaml").read_text())
    uni = protocol["data"]["universe"]
    pw = protocol["data"]["price_window"]
    sample = protocol["data"]["sample"]
    hac = protocol["regression"]["hac_lags"]
    roll_w = protocol["regression"]["rolling_beta_window"]
    lb_lags = protocol["diagnostics"]["ljung_box_lags"]
    train, test = protocol["evaluation"]["train"], protocol["evaluation"]["test"]
    bt_cfg = protocol["backtest"]

    bundle = build_bundle(uni, pw["start"], pw["end"], ROOT / "data_cache")
    factors = bundle.factors.loc[sample["start"]:sample["end"]]
    returns = bundle.returns.loc[sample["start"]:sample["end"]]
    excess = excess_returns(returns, factors["RF"])
    print(f"sample: {returns.index[0]} .. {returns.index[-1]}  ({len(returns)} months, {returns.shape[1]} tickers)")

    # ---- 1. full-sample factor regressions, all models x all stocks ----
    rows = []
    fits = {}
    for model, fnames in MODELS.items():
        for t in uni:
            fit = fit_factor_model(excess[t], factors, fnames, model, hac_lags=hac)
            fits[(model, t)] = fit
            row = {"ticker": t, "model": model, "r2": fit.r2, "adj_r2": fit.adj_r2, "nobs": fit.nobs}
            for k in fit.params.index:
                row[f"beta_{k}"] = fit.params[k]
                row[f"t_{k}"] = fit.tstats[k]
                row[f"p_{k}"] = fit.pvalues[k]
            rows.append(row)
    loadings = pd.DataFrame(rows)
    # Benjamini-Hochberg across the 16 alphas of each model
    loadings["alpha_bh_q"] = np.nan
    for model in MODELS:
        mask = loadings["model"] == model
        loadings.loc[mask, "alpha_bh_q"] = benjamini_hochberg(loadings.loc[mask, "p_const"].to_numpy())
    loadings.to_csv(RESULTS / "factor_loadings.csv", index=False)

    # ---- 2. AAPL deep dive: fitted vs actual, residuals, diagnostics, rolling beta ----
    aapl_ff3 = fits[("FF3", "AAPL")]
    deep = pd.DataFrame({
        "month": excess.index.astype(str),
        "actual_excess": excess["AAPL"].values,
        "fitted_ff3": aapl_ff3.fitted.reindex(excess.index).values,
        "resid_ff3": aapl_ff3.resid.reindex(excess.index).values,
    })
    deep.to_csv(RESULTS / "aapl_ff3_timeseries.csv", index=False)
    rb = rolling_beta(excess["AAPL"], factors["Mkt-RF"], window=roll_w)
    rb.rename("rolling_beta").to_csv(RESULTS / "aapl_rolling_beta.csv", index_label="month")
    diagnostics = {
        "AAPL_FF3": {
            "jarque_bera": dg.jarque_bera(aapl_ff3.resid),
            "ljung_box": dg.ljung_box(aapl_ff3.resid, lags=lb_lags),
        }
    }
    write_json(RESULTS / "aapl_diagnostics.json", diagnostics)

    # ---- 3. out-of-sample evaluation (train betas applied to test, touched once) ----
    f_train = factors.loc[train["start"]:train["end"]]
    f_test = factors.loc[test["start"]:test["end"]]
    x_train = excess.loc[train["start"]:train["end"]]
    x_test = excess.loc[test["start"]:test["end"]]
    oos_rows = []
    for model, fnames in MODELS.items():
        for t in uni:
            fit = fit_factor_model(x_train[t], f_train, fnames, model, hac_lags=hac)
            Xte = pd.concat([pd.Series(1.0, index=f_test.index, name="const"), f_test[fnames]], axis=1)
            pred = Xte @ fit.params
            sse = float(((x_test[t] - pred) ** 2).sum())
            sst = float(((x_test[t] - x_train[t].mean()) ** 2).sum())
            oos_rows.append({"ticker": t, "model": model,
                             "oos_r2": 1 - sse / sst, "train_r2": fit.r2,
                             "alpha_train": fit.params["const"],
                             "alpha_train_p": fit.pvalues["const"]})
    oos = pd.DataFrame(oos_rows)
    oos.to_csv(RESULTS / "oos_evaluation.csv", index=False)
    oos_summary = oos.groupby("model")[["oos_r2", "train_r2"]].mean().round(6)
    oos_summary.to_csv(RESULTS / "oos_summary.csv")

    # ---- 4. backtest: top-5 12-1 momentum tilt, 2021-2023, cost grid ----
    signals = bt.momentum_signal(bundle.prices)
    months = pd.period_range(bt_cfg["evaluation_window"]["start"],
                             bt_cfg["evaluation_window"]["end"], freq="M")
    spy = bundle_spy = None
    import yfinance as yf
    spy_raw = yf.download("SPY", start=pw["start"], end=pw["end"], interval="1mo",
                          auto_adjust=True, progress=False)
    if isinstance(spy_raw.columns, pd.MultiIndex):
        spy_raw.columns = spy_raw.columns.get_level_values(0)
    spy_ret = spy_raw["Close"].copy()
    spy_ret.index = spy_ret.index.to_period("M")
    spy_ret = spy_ret.pct_change().dropna()

    grid = {}
    for bps in bt_cfg["cost_grid_bps"]:
        res = bt.run_backtest(bundle.returns, signals, months,
                              n_positions=5, cost_bps=float(bps))
        grid[str(bps)] = res
    head = grid[str(bt_cfg["headline_cost_bps"])]

    ew_monthly = bundle.returns.loc[months].mean(axis=1)  # equal-weight, monthly rebalanced
    bench = pd.DataFrame({
        "strategy_gross": grid["0"]["monthly"]["gross"],
        "strategy_net": head["monthly"]["net"],
        "equal_weight_16": ew_monthly,
        "spy": spy_ret.reindex(months),
        "turnover": head["monthly"]["turnover"],
    })
    bench.index = bench.index.astype(str)
    bench.to_csv(RESULTS / "backtest_monthly.csv", index_label="month")
    curves = (1 + bench[["strategy_gross", "strategy_net", "equal_weight_16", "spy"]]).cumprod()
    curves.to_csv(RESULTS / "backtest_equity_curves.csv", index_label="month")
    pd.DataFrame({"month": [str(m) for m in months], "holdings": head["holdings"]}).to_csv(
        RESULTS / "backtest_holdings.csv", index=False)

    rf_bt = factors["RF"].reindex(months)
    stats_rows = []
    for col in ["strategy_gross", "strategy_net", "equal_weight_16", "spy"]:
        s = bt.performance_stats(bench[col].dropna(), rf=rf_bt)
        s["series"] = col
        stats_rows.append(s)
    for bps, res in grid.items():
        s = bt.performance_stats(res["monthly"]["net"], rf=rf_bt)
        stats_rows.append({"series": f"net_cost_{bps}bps", **s,
                           "avg_annual_turnover": float(res["monthly"]["turnover"].mean() * 12)})
    stats_df = pd.DataFrame(stats_rows).set_index("series")
    stats_df.to_csv(RESULTS / "backtest_stats.csv")

    # ---- 5. provenance + manifest ----
    provenance = {"protocol": protocol, "retrieval": bundle.retrieval,
                  "sample_months": len(returns), "tickers": uni}
    write_json(RESULTS / "provenance.json", provenance)

    manifest = {}
    for f in sorted(RESULTS.glob("*")):
        if f.is_file() and f.name not in {"manifest.json"}:
            manifest[f.name] = hashlib.sha256(f.read_bytes()).hexdigest()
    write_json(RESULTS / "manifest.json", manifest)

    # ---- 6. site data export ----
    export_site(loadings, deep, rb, diagnostics, oos, oos_summary, bench, curves,
                stats_df, uni, factors, bundle.retrieval, protocol)
    print("artifacts:", sorted(manifest))
    print(oos_summary)
    print(stats_df.round(4))


def export_site(loadings, deep, rb, diagnostics, oos, oos_summary, bench, curves,
                stats_df, uni, factors, retrieval, protocol) -> None:
    write_json(SITE_DATA / "meta.json", {
        "title": "Multi-Factor Equity Pricing",
        "universe": uni, "sample": protocol["data"]["sample"],
        "train": protocol["evaluation"]["train"], "test": protocol["evaluation"]["test"],
        "models": {k: v for k, v in MODELS.items()},
        "retrieved_at_utc": retrieval["retrieved_at_utc"],
        "hac_lags": protocol["regression"]["hac_lags"],
        "backtest": protocol["backtest"],
    })
    ld = loadings.copy()
    ld.columns = [c.replace("Mkt-RF", "MKT") for c in ld.columns]
    write_json(SITE_DATA / "loadings.json", ld.round(6).to_dict(orient="records"))
    write_json(SITE_DATA / "aapl_timeseries.json", {
        "months": deep["month"].tolist(),
        "actual": deep["actual_excess"].round(6).tolist(),
        "fitted": deep["fitted_ff3"].round(6).tolist(),
        "resid": deep["resid_ff3"].round(6).tolist(),
        "rolling_beta_months": [str(m) for m in rb.index],
        "rolling_beta": rb.round(4).tolist(),
        "diagnostics": diagnostics,
    })
    write_json(SITE_DATA / "oos.json", {
        "per_stock": oos.round(6).to_dict(orient="records"),
        "summary": oos_summary.reset_index().round(6).to_dict(orient="records"),
    })
    write_json(SITE_DATA / "backtest.json", {
        "months": bench.index.tolist(),
        "curves": {c: curves[c].round(5).tolist() for c in curves.columns},
        "monthly": {c: bench[c].round(6).tolist() for c in ["strategy_net", "equal_weight_16", "spy", "turnover"]},
        "stats": stats_df.reset_index().round(6).to_dict(orient="records"),
    })


if __name__ == "__main__":
    main()
